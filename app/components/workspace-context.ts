import type { DocumentDetail, DocumentVersion } from "../lib/documents";
import type { AccessModule } from "../lib/access-control";
import type { ChangeEvent, Dispatch, FormEvent, ReactNode, SetStateAction } from "react";

export type Tab = "dashboard" | "profile" | "compare" | "documents" | "templates" | "template-editor" | "editor" | "history" | "approvals" | "company" | "users";
export type CompanyWorkspace = { id: string; name: string; role: "admin" | "member" };
export type TemplateDesign = { theme: "classic" | "modern" | "minimal"; accent: string };
export type Template = { id: number; title: string; desc: string; body: string; access: string; owner?: string; locked?: boolean; category?: "document" | "table"; design?: TemplateDesign };
export type Change = { id: number; type: string; title: string; description: string; a: string; b: string };
export type AiComparisonFinding = { changeId: number; whatChanged: string; impact: string; severity: "low" | "medium" | "high"; recommendation: string };
export type AiComparison = { summary: string; overallRisk: "low" | "medium" | "high"; findings: AiComparisonFinding[] };
export type Report = { id: number; isSaved?: boolean; summary: string; metrics: { total: number; conflicts: number; lost: number; news: number; changed: number }; changes: Change[]; aiAnalysis?: AiComparison; aiAnalysisError?: string };
export type SessionUser = { id: string; name: string; email: string; role: string; permissions?: AccessModule[] | null; platformRole?: "operator" | null; company?: string; position?: string; avatar?: string | null; emailVerified?: boolean };
export type UserRow = { name: string; email: string; role: string; permissions?: AccessModule[]; emailVerified?: boolean };
export type HistoryRow = { title: string; type: string; meta: string; documentId?: string };
export type AuthMode = "login" | "register" | "verify" | "reset" | "reset-confirm" | null;

export type WorkspaceProps = {
  nav: [Tab, string][];
  tab: Tab;
  setTab: Dispatch<SetStateAction<Tab>>;
  goBackTab: () => void;
  canGoBack: boolean;
  workspaces: CompanyWorkspace[];
  setWorkspaces: Dispatch<SetStateAction<CompanyWorkspace[]>>;
  activeWorkspaceId: string | null;
  setActiveWorkspaceId: Dispatch<SetStateAction<string | null>>;
  setOpenTemplate: Dispatch<SetStateAction<Template | null>>;
  sessionUser: SessionUser | null;
  setSessionUser: Dispatch<SetStateAction<SessionUser | null>>;
  logout: () => Promise<void>;
  setAuthMode: Dispatch<SetStateAction<AuthMode>>;
  a: string; setA: Dispatch<SetStateAction<string>>;
  b: string; setB: Dispatch<SetStateAction<string>>;
  report: Report | null;
  analysisBusy: boolean;
  analysisSources: { a: string; b: string };
  templates: Template[];
  editorText: string; setEditorText: Dispatch<SetStateAction<string>>;
  editorTitle: string; setEditorTitle: Dispatch<SetStateAction<string>>;
  editorKey: number;
  documentId: string | null;
  editorVersion: number;
  editorBusy: boolean;
  newDocument: (workspaceId?: string) => void;
  openDocument: (document: DocumentDetail, version?: DocumentVersion) => void;
  onDocumentsSaved: () => Promise<void>;
  onDocumentDeleted: (id: string) => void;
  openTemplate: Template | null;
  notice: string; setNotice: Dispatch<SetStateAction<string>>;
  history: HistoryRow[];
  setHistory: (history: HistoryRow[] | ((current: HistoryRow[]) => HistoryRow[])) => void;
  templateQuery: string;
  setTemplateQuery: Dispatch<SetStateAction<string>>;
  filteredTemplateCount: number;
  users: UserRow[];
  templateTitle: string; setTemplateTitle: Dispatch<SetStateAction<string>>;
  templateDesc: string; setTemplateDesc: Dispatch<SetStateAction<string>>;
  templateBody: string; setTemplateBody: Dispatch<SetStateAction<string>>;
  templateAccess: string; setTemplateAccess: Dispatch<SetStateAction<string>>;
  templateCategory: "document" | "table"; setTemplateCategory: Dispatch<SetStateAction<"document" | "table">>;
  templateDesign: TemplateDesign; setTemplateDesign: Dispatch<SetStateAction<TemplateDesign>>;
  templateEditingId: number | null; setTemplateEditingId: Dispatch<SetStateAction<number | null>>;
  beginTemplateDesign: (template?: Template) => void;
  startAnalysis: (withAi?: boolean) => Promise<void>;
  openAnalysis: (id: string) => Promise<void>;
  handleFile: (setter: (value: string) => void) => (event: ChangeEvent<HTMLInputElement>) => Promise<void>;
  editTemplate: (template: Template) => Promise<void>;
  saveEditor: () => Promise<void>;
  exportReport: () => Promise<void>;
  createTemplate: (event: FormEvent<HTMLFormElement>) => Promise<void>;
  changeRole: (email: string, role: string) => Promise<void>;
  changePermissions: (email: string, permissions: AccessModule[]) => Promise<void>;
  deleteTemplate: (template: Template) => Promise<void>;
  downloadText: (text: string, filename: string, type?: string) => void;
  submitAuth: (event: FormEvent<HTMLFormElement>) => Promise<void>;
  authMode: AuthMode;
  authName: string; setAuthName: Dispatch<SetStateAction<string>>;
  authEmail: string; setAuthEmail: Dispatch<SetStateAction<string>>;
  authPassword: string; setAuthPassword: Dispatch<SetStateAction<string>>;
  authToken: string; setAuthToken: Dispatch<SetStateAction<string>>;
  authBusy: boolean;
  resendVerification: () => Promise<void>;
  cards: ReactNode;
};
